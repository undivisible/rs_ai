//! Provider-independent pieces of an authorization-code transaction.
//!
//! Generate a fresh attempt for every transaction. The caller owns
//! transaction expiry, one-time use, callback parsing and secure storage. These
//! primitives do not establish that a provider permits a browser client or a
//! particular redirect URI, nor do they validate OpenID Connect ID tokens.
//! If navigation destroys the page, retain the generated values in protected,
//! session-bound storage using `into_parts` and reconstruct the attempt on return; remove them
//! after success, failure, or expiry. Never put the verifier in the authorization URL.

use base64::{engine::general_purpose::URL_SAFE_NO_PAD, Engine as _};
use sha2::{Digest, Sha256};
use url::Url;

/// PKCE verifier and CSRF state for one authorization attempt.
///
/// Treat the verifier and state as secrets and bind them to the initiating
/// browser session. Never send the verifier to the authorization endpoint.
pub struct AuthorizationAttempt {
    verifier: String,
    state: String,
}

impl AuthorizationAttempt {
    /// Generate an attempt using the operating system CSPRNG or browser Web Crypto.
    pub fn generate() -> Result<Self, getrandom::Error> {
        let mut bytes = [0u8; 64];
        getrandom::getrandom(&mut bytes)?;
        let mut verifier = [0u8; 32];
        let mut state = [0u8; 32];
        verifier.copy_from_slice(&bytes[..32]);
        state.copy_from_slice(&bytes[32..]);
        Ok(Self::from_random_bytes(verifier, state))
    }

    /// Construct an attempt from two independent 32-byte CSPRNG outputs.
    ///
    /// These must be freshly generated for each attempt, not derived from user
    /// input or reused. A 32-byte verifier encodes to 43 RFC 7636-safe characters.
    pub fn from_random_bytes(verifier: [u8; 32], state: [u8; 32]) -> Self {
        Self {
            verifier: URL_SAFE_NO_PAD.encode(verifier),
            state: URL_SAFE_NO_PAD.encode(state),
        }
    }

    /// Consume the attempt for protected session-bound storage across navigation.
    /// The returned verifier is secret; never send it to the authorization endpoint.
    pub fn into_parts(self) -> (String, String) {
        (self.verifier, self.state)
    }

    /// Restore previously stored values generated by this API.
    pub fn from_parts(verifier: String, state: String) -> Result<Self, InvalidAttempt> {
        let valid = |value: &str| {
            URL_SAFE_NO_PAD
                .decode(value)
                .is_ok_and(|bytes| bytes.len() == 32 && URL_SAFE_NO_PAD.encode(bytes) == value)
        };
        if !valid(&verifier) || !valid(&state) {
            return Err(InvalidAttempt);
        }
        Ok(Self { verifier, state })
    }

    /// S256 challenge to send with `code_challenge_method=S256`.
    pub fn code_challenge(&self) -> String {
        URL_SAFE_NO_PAD.encode(Sha256::digest(self.verifier.as_bytes()))
    }

    /// State to send in the authorization request.
    pub fn state(&self) -> &str {
        &self.state
    }

    /// Build an authorization request, retaining the exact redirect URI string.
    ///
    /// The endpoint must be HTTPS, except for loopback HTTP development servers.
    /// Existing non-OAuth query parameters are preserved. The caller must use
    /// the same redirect URI in the subsequent token exchange.
    pub fn authorization_url(
        &self,
        endpoint: &str,
        client_id: &str,
        redirect_uri: &str,
        scopes: &[&str],
    ) -> Result<Url, AuthorizationUrlError> {
        let mut url = Url::parse(endpoint).map_err(|_| AuthorizationUrlError::InvalidEndpoint)?;
        let loopback = matches!(url.host_str(), Some("localhost" | "127.0.0.1" | "[::1]"));
        if !(url.scheme() == "https" || url.scheme() == "http" && loopback)
            || url.host_str().is_none()
            || !url.username().is_empty()
            || url.password().is_some()
            || url.fragment().is_some()
        {
            return Err(AuthorizationUrlError::InvalidEndpoint);
        }
        const RESERVED: &[&str] = &[
            "response_type",
            "client_id",
            "redirect_uri",
            "scope",
            "state",
            "code_challenge",
            "code_challenge_method",
        ];
        if url
            .query_pairs()
            .any(|(key, _)| RESERVED.contains(&key.as_ref()))
        {
            return Err(AuthorizationUrlError::ConflictingParameter);
        }
        if client_id.is_empty() {
            return Err(AuthorizationUrlError::InvalidClientId);
        }
        let redirect =
            Url::parse(redirect_uri).map_err(|_| AuthorizationUrlError::InvalidRedirectUri)?;
        if redirect.fragment().is_some() {
            return Err(AuthorizationUrlError::InvalidRedirectUri);
        }
        if scopes.iter().any(|scope| {
            scope.is_empty()
                || !scope
                    .bytes()
                    .all(|b| b == 0x21 || (0x23..=0x5b).contains(&b) || (0x5d..=0x7e).contains(&b))
        }) {
            return Err(AuthorizationUrlError::InvalidScope);
        }
        {
            let mut query = url.query_pairs_mut();
            query
                .append_pair("response_type", "code")
                .append_pair("client_id", client_id)
                .append_pair("redirect_uri", redirect_uri)
                .append_pair("state", &self.state)
                .append_pair("code_challenge", &self.code_challenge())
                .append_pair("code_challenge_method", "S256");
            if !scopes.is_empty() {
                query.append_pair("scope", &scopes.join(" "));
            }
        }
        Ok(url)
    }

    /// Validate the returned state before processing either a code or error.
    ///
    /// The caller must also ensure the attempt has not expired or been used.
    pub fn validate_state(&self, returned_state: Option<&str>) -> bool {
        returned_state == Some(self.state.as_str())
    }

    /// Consume the attempt and return its verifier after validating state.
    /// A mismatch consumes the attempt too, preventing reuse by the caller.
    pub fn into_verifier(self, returned_state: Option<&str>) -> Result<String, StateMismatch> {
        if self.validate_state(returned_state) {
            Ok(self.verifier)
        } else {
            Err(StateMismatch)
        }
    }
}

/// The callback state is missing or does not match the pending attempt.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[error("OAuth state mismatch")]
pub struct StateMismatch;

/// Stored verifier or state is not a canonical 32-byte generated value.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[error("invalid stored OAuth attempt")]
pub struct InvalidAttempt;

/// Invalid input for an authorization request.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum AuthorizationUrlError {
    #[error("invalid or insecure authorization endpoint")]
    InvalidEndpoint,
    #[error("authorization endpoint contains a conflicting OAuth parameter")]
    ConflictingParameter,
    #[error("client ID is empty")]
    InvalidClientId,
    #[error("redirect URI must be absolute and contain no fragment")]
    InvalidRedirectUri,
    #[error("invalid OAuth scope token")]
    InvalidScope,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn challenge_matches_rfc_7636_example() {
        let attempt = AuthorizationAttempt {
            verifier: "dBjftJeZ4CVP-mB92K27uhbUJU1p1r_wW1gFWFOEjXk".into(),
            state: "state".into(),
        };
        assert_eq!(
            attempt.code_challenge(),
            "E9Melhoa2OwvFrEMTJguCHaoeK1t8URWbuGJSstw-cM"
        );
    }

    #[test]
    fn generated_values_are_url_safe_and_state_is_required() {
        let attempt = AuthorizationAttempt::from_random_bytes([255; 32], [42; 32]);
        assert_eq!(attempt.verifier.len(), 43);
        assert_eq!(attempt.state().len(), 43);
        assert!(attempt
            .verifier
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_'));
        assert!(!attempt.validate_state(None));
        assert!(!attempt.validate_state(Some("wrong")));
        assert_eq!(attempt.into_verifier(Some("wrong")), Err(StateMismatch));

        let attempt = AuthorizationAttempt::from_random_bytes([255; 32], [42; 32]);
        let state = attempt.state().to_owned();
        assert!(attempt.into_verifier(Some(&state)).is_ok());
    }

    #[test]
    fn builds_encoded_request_with_exact_redirect_and_pkce() {
        let attempt = AuthorizationAttempt::from_random_bytes([255; 32], [42; 32]);
        let redirect = "https://example.com/callback?x=a%2Fb&y=1";
        let url = attempt
            .authorization_url(
                "https://auth.example/authorize?audience=a%2Fb",
                "client & id",
                redirect,
                &["openid", "profile:read"],
            )
            .unwrap();
        let pairs: std::collections::HashMap<_, _> = url.query_pairs().into_owned().collect();
        assert_eq!(pairs["audience"], "a/b");
        assert_eq!(pairs["redirect_uri"], redirect);
        assert_eq!(pairs["client_id"], "client & id");
        assert_eq!(pairs["scope"], "openid profile:read");
        assert_eq!(pairs["response_type"], "code");
        assert_eq!(pairs["state"], attempt.state());
        assert_eq!(pairs["code_challenge"], attempt.code_challenge());
        assert_eq!(pairs["code_challenge_method"], "S256");
        assert!(!url.as_str().contains(&attempt.verifier));
    }

    #[test]
    fn rejects_ambiguous_or_invalid_requests() {
        let a = AuthorizationAttempt::from_random_bytes([1; 32], [2; 32]);
        let build = |e, c, r, s: &[&str]| a.authorization_url(e, c, r, s).map(|_| ());
        assert_eq!(
            build("https://auth.test/?%73tate=evil", "c", "app:/cb", &[]),
            Err(AuthorizationUrlError::ConflictingParameter)
        );
        assert_eq!(
            build("http://auth.test/", "c", "app:/cb", &[]),
            Err(AuthorizationUrlError::InvalidEndpoint)
        );
        assert_eq!(
            build("https://auth.test/#fragment", "c", "app:/cb", &[]),
            Err(AuthorizationUrlError::InvalidEndpoint)
        );
        assert_eq!(
            build("https://auth.test/", "", "app:/cb", &[]),
            Err(AuthorizationUrlError::InvalidClientId)
        );
        assert_eq!(
            build("https://auth.test/", "c", "/relative", &[]),
            Err(AuthorizationUrlError::InvalidRedirectUri)
        );
        assert_eq!(
            build("https://auth.test/", "c", "app:/cb#f", &[]),
            Err(AuthorizationUrlError::InvalidRedirectUri)
        );
        assert_eq!(
            build("https://auth.test/", "c", "app:/cb", &["bad scope"]),
            Err(AuthorizationUrlError::InvalidScope)
        );
        assert!(build("http://localhost:1234/", "c", "app:/cb", &[]).is_ok());
    }

    #[test]
    fn secure_generation_produces_distinct_attempts() {
        let a = AuthorizationAttempt::generate().unwrap();
        let b = AuthorizationAttempt::generate().unwrap();
        assert_ne!(a.state(), b.state());
        assert_ne!(a.verifier, b.verifier);
        assert_ne!(a.state(), a.verifier);
    }

    #[test]
    fn stored_attempt_round_trips_and_rejects_malformed_values() {
        let attempt = AuthorizationAttempt::generate().unwrap();
        let challenge = attempt.code_challenge();
        let (verifier, state) = attempt.into_parts();
        assert!(AuthorizationAttempt::from_parts("short".into(), state.clone()).is_err());
        let restored = AuthorizationAttempt::from_parts(verifier, state.clone()).unwrap();
        assert_eq!(restored.code_challenge(), challenge);
        assert!(restored.into_verifier(Some(&state)).is_ok());
    }
}
